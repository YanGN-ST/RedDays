"""重写 README 的「数据维护状态」区块（标记对之间的内容）。

由 publish workflow 在每次同步后运行：范围与时间全部实时读取，
数据变化时随 chore(sync) 提交一起更新，README 无需人工维护。
"""

import json
import os
import subprocess
import sys
import datetime as dt

sys.path.insert(0, os.path.abspath(os.path.dirname(__file__)))
from paths import workspace_path  # noqa: E402

START = "<!-- data-status:start -->"
END = "<!-- data-status:end -->"


def _nonempty_years() -> list[int]:
    years = []
    for f in os.listdir(workspace_path("data")):
        if not f.endswith(".json"):
            continue
        with open(workspace_path("data", f), encoding="utf-8") as fh:
            if json.load(fh).get("days"):
                years.append(int(f[:4]))
    return sorted(years)


def _hk_years() -> list[int]:
    return sorted(
        int(f[:4])
        for f in os.listdir(workspace_path("data", "hk"))
        if f.endswith(".json")
    )


def _last_sync() -> str:
    out = subprocess.run(
        ["git", "log", "-1", "--format=%cI", "--", "data/"],
        capture_output=True,
        text=True,
        cwd=workspace_path(),
    )
    line = out.stdout.strip()
    return line[:10] if line else dt.date.today().isoformat()


def build_block() -> str:
    today = dt.date.today()
    cn = _nonempty_years()
    hk = _hk_years()
    with open(workspace_path("data", "losar.json"), encoding="utf-8") as f:
        losar_years = sorted(int(y) for y in json.load(f)["losar"])
    lines = [
        f"As of {today.isoformat()} (generated by `scripts/readme_status.py`):",
        "",
        f"- **Last maintained:** {_last_sync()}. GitHub Actions checks official sources daily and rolls calendar windows forward.",
        "- **Coverage:**",
        f"  - Mainland statutory holidays: {cn[0]}–{cn[-1]} (`data/*.json`)",
        f"  - Hong Kong public holidays: {hk[0]}–{hk[-1]} (`data/hk/*.json`, official 1823 data)",
        f"  - Lunar, Hijri, ethnic and Christian calendars: rolling window, currently {today.year - 1}–{today.year + 2}",
        f"  - Daily almanac: current and next year, currently {today.year}–{today.year + 1}",
        f"  - Tibetan New Year: {losar_years[0]}–{losar_years[-1]} (`data/losar.json`), using a Phugpa reference implementation",
        "- New annual data is published after official notices are parsed and validation passes. Failed validation blocks publication and opens an alert issue.",
        "",
    ]
    return START + "\n" + "\n".join(lines) + END + "\n"


def main() -> None:
    path = workspace_path("README.md")
    with open(path, encoding="utf-8") as f:
        text = f.read()
    if START not in text or END not in text:
        raise SystemExit("README.md is missing the data-status markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(head + build_block() + tail)
    print("readme: data-status block regenerated")


if __name__ == "__main__":
    main()
